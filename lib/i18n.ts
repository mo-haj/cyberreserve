// Every page shows exactly one language; the visitor switches with the
// language link in the header (stored in the cr_lang cookie).
//
// Pure module: safe to import from server and client components.

export type Locale = 'ar' | 'en';
export const LOCALES: Locale[] = ['ar', 'en'];
/** Language for visitors who have not picked one yet (the switch in the header sets cr_lang). */
export const DEFAULT_LOCALE: Locale = 'en';
export const LOCALE_COOKIE = 'cr_lang';

export function isLocale(value: unknown): value is Locale {
  return value === 'ar' || value === 'en';
}

export function dirOf(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

/** Picks the field in the visitor's language from a bilingual record. */
export function pick(locale: Locale, en: string, ar: string): string {
  return locale === 'ar' ? ar : en;
}

